import React from 'react';
import { Bar, BarChart, CartesianGrid, Cell, Line, LineChart, ResponsiveContainer, Tooltip, XAxis, YAxis } from 'recharts';
import { SOURCES, USERS, rng } from '../lib/mock.js';
import { C, Card, ChartTip, Legend, Stat } from '../components/ui.jsx';

const axis = { stroke: '#9a9a9a', fontSize: 12, tickLine: false };
const KEYS = ['metadata', 'trending', 'als'];
const COLOR = { metadata: C.ink, trending: C.mid, als: C.red };

const r = rng(99);
const scoreDist = Array.from({ length: 12 }, (_, i) => ({ bin: (i / 12 + 0.04).toFixed(2), metadata: Math.round(20 + 80 * Math.exp(-Math.pow((i - 8) / 2.4, 2)) + r() * 8), trending: Math.round(18 + 70 * Math.exp(-Math.pow((i - 5) / 3, 2)) + r() * 8), als: Math.round(15 + 90 * Math.exp(-Math.pow((i - 6.5) / 2.2, 2)) + r() * 8) }));

const final = KEYS.map((k) => ({ name: SOURCES[k], key: k, value: USERS.reduce((a, u) => a + u.recs.filter((x) => x.sources.includes(k)).length, 0) }));
const gen = KEYS.map((k) => ({ name: SOURCES[k], key: k, value: USERS.length * 8 }));

const overlap = [
  ['Metadata only', 41], ['Trending only', 27], ['ALS only', 48],
  ['Metadata + ALS', 14], ['Metadata + Trending', 6], ['Trending + ALS', 9], ['All three', 3],
].map(([name, value]) => ({ name, value }));

const survival = KEYS.map((k) => ({ name: SOURCES[k], generated: USERS.length * 8, kept: USERS.reduce((a, u) => a + u.recs.filter((x) => x.sources.includes(k)).length, 0) }));

export default function Engines() {
  return (
    <>
      <div className="grid g3">
        {[
          ['metadata', 'Metadata engine', 'Content-based. Matches category, year and rating to what the user watches.', '82 ms'],
          ['trending', 'Trending and freshness', 'What is rising across the platform over the last 14 days.', '38 ms'],
          ['als', 'ALS matrix factorization', 'Collaborative filtering from the saved model. Weak for brand new users.', '61 ms'],
        ].map(([k, t, d, lat]) => (
          <div className="card" key={k} style={{ borderTop: `5px solid ${COLOR[k]}` }}>
            <div className="card-head"><div><h3>{t}</h3><p>{d}</p></div></div>
            <div className="card-body">
              <div className="row" style={{ gap: 28 }}>
                <div><div className="muted">Candidates</div><b className="num" style={{ fontFamily: 'var(--font-display)', fontSize: 26 }}>{gen.find((g) => g.key === k).value}</b></div>
                <div><div className="muted">In final top 5</div><b className="num" style={{ fontFamily: 'var(--font-display)', fontSize: 26 }}>{final.find((g) => g.key === k).value}</b></div>
                <div><div className="muted">p95 latency</div><b className="num" style={{ fontFamily: 'var(--font-display)', fontSize: 26 }}>{lat}</b></div>
              </div>
            </div>
          </div>
        ))}
      </div>

      <div className="grid g2">
        <Card title="Candidate score distribution" sub="How confident each engine is in what it proposes">
          <Legend items={[['Metadata', C.ink], ['Trending', C.mid, true], ['ALS', C.red]]} />
          <ResponsiveContainer width="100%" height={280}>
            <LineChart data={scoreDist}>
              <CartesianGrid vertical={false} stroke={C.line} />
              <XAxis dataKey="bin" {...axis} />
              <YAxis {...axis} />
              <Tooltip content={<ChartTip />} />
              <Line dataKey="metadata" name="Metadata" stroke={C.ink} strokeWidth={2.5} dot={false} isAnimationActive={false} />
              <Line dataKey="trending" name="Trending" stroke={C.mid} strokeWidth={2.5} strokeDasharray="6 4" dot={false} isAnimationActive={false} />
              <Line dataKey="als" name="ALS" stroke={C.red} strokeWidth={2.5} dot={false} isAnimationActive={false} />
            </LineChart>
          </ResponsiveContainer>
        </Card>
        <Card title="How many candidates survive to the top 5" sub="Generated by each engine vs. kept after pooling and re-ranking">
          <Legend items={[['Generated', C.line], ['Kept in top 5', C.red]]} />
          <ResponsiveContainer width="100%" height={280}>
            <BarChart data={survival}>
              <CartesianGrid vertical={false} stroke={C.line} />
              <XAxis dataKey="name" {...axis} />
              <YAxis {...axis} />
              <Tooltip content={<ChartTip />} cursor={{ fill: '#f4f4f4' }} />
              <Bar isAnimationActive={false} dataKey="generated" name="Generated" fill="#d2d2d2" radius={[4, 4, 0, 0]} barSize={36} />
              <Bar isAnimationActive={false} dataKey="kept" name="Kept in top 5" fill={C.red} radius={[4, 4, 0, 0]} barSize={36} />
            </BarChart>
          </ResponsiveContainer>
        </Card>
      </div>

      <Card title="Overlap between engines" sub="Share of pooled candidates proposed by each combination. Overlap is what dedupe removes.">
        <ResponsiveContainer width="100%" height={280}>
          <BarChart data={overlap} layout="vertical" margin={{ right: 24 }}>
            <CartesianGrid horizontal={false} stroke={C.line} />
            <XAxis type="number" {...axis} tickFormatter={(v) => v + '%'} />
            <YAxis type="category" dataKey="name" width={150} {...axis} stroke={C.ink} />
            <Tooltip content={<ChartTip fmt={(v) => v + '%'} />} cursor={{ fill: '#f4f4f4' }} />
            <Bar isAnimationActive={false} dataKey="value" name="Share" radius={[0, 4, 4, 0]} barSize={18}>
              {overlap.map((o, i) => <Cell key={o.name} fill={i < 3 ? C.ink : C.red} />)}
            </Bar>
          </BarChart>
        </ResponsiveContainer>
        <Legend items={[['Single engine', C.ink], ['Proposed by 2+ engines (deduplicated)', C.red]]} />
      </Card>
    </>
  );
}
